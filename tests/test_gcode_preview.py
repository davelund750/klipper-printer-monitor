"""Tests for gcode_preview.py, the layer preview's G-code reader.
Run with: python3 -m unittest discover -s tests"""

import io
import math
import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "server"))

import gcode_preview  # noqa: E402


def read(text):
    return gcode_preview.read_gcode(io.BytesIO(text.encode()))


# A small Creality-Print-like file: a purge line before the first layer
# marker, two layers, relative extrusion, a travel move, and settings at the end.
SAMPLE = """; generated by Creality_Print V7.3.0
M83
G90
G1 Z0.3 F600
G1 X0 Y-1 F6000
G1 X50 Y-1 E5
;LAYER_CHANGE
;Z:0.2
G1 Z0.2
G1 X10 Y10 F6000
G1 X20 Y10 E1
G1 X20 Y20 E1
G1 X30 Y30
G1 X10 Y20 E-0.5
;LAYER_CHANGE
;Z:0.4
G1 Z0.4
G1 X10 Y10
G1 X20 Y10 E1
; CONFIG_BLOCK_START
; filament_colour = #C33F31
; extruder_colour = ""
; CONFIG_BLOCK_END
"""

# The same, with Creality Print's time marks at the end of each layer.
TIMED = SAMPLE.replace(";LAYER_CHANGE\n;Z:0.4", ";TIME_ELAPSED:12\n;LAYER_CHANGE\n;Z:0.4").replace(
    "; CONFIG_BLOCK_START", ";TIME_ELAPSED:30\n; CONFIG_BLOCK_START")


class ReadGcodeTest(unittest.TestCase):
    def test_layers_and_printing_moves(self):
        index = read(SAMPLE)
        # The purge line, then the two marked layers.
        self.assertEqual([round(layer.z, 2) for layer in index.layers], [0.3, 0.2, 0.4])
        purge, first, second = index.layers
        self.assertEqual(list(purge.segs), [0, -1, 50, -1])
        # Travel moves and retractions aren't drawn.
        self.assertEqual([round(v) for v in first.segs], [10, 10, 20, 10, 20, 10, 20, 20])
        self.assertEqual(len(second.ends), 1)

    def test_extent_leaves_out_the_purge_line(self):
        self.assertEqual(read(SAMPLE).bounds, [10, 10, 20, 20])

    def test_colour_from_the_settings(self):
        self.assertEqual(read(SAMPLE).colours, ["#C33F31"])

    def test_offsets_say_how_far_through_a_layer(self):
        index = read(SAMPLE)
        first = index.layers[1]
        text = SAMPLE.encode()
        # Each segment ends at the end of its line in the file.
        self.assertEqual(first.ends[0], text.index(b"G1 X20 Y10 E1\n") + len(b"G1 X20 Y10 E1\n"))
        self.assertEqual(index.layer_at(first.start), 1)
        self.assertEqual(index.layer_at(first.ends[1]), 1)
        self.assertEqual(index.layer_at(index.layers[2].start + 1), 2)
        self.assertEqual(index.layer_at(0), 0)

    def test_absolute_extrusion(self):
        index = read("M82\n;LAYER_CHANGE\nG1 X0 Y0\nG1 X10 Y0 E1\nG1 X10 Y10 E1\nG92 E0\nG1 X0 Y10 E0.5\n")
        self.assertEqual(len(index.layers[0].ends), 2)  # E1 -> E1 isn't extruding

    def test_arcs_become_short_segments(self):
        # A half circle of radius 10 around (10, 0), counter-clockwise.
        index = read("M83\n;LAYER_CHANGE\nG1 X0 Y0\nG3 X20 Y0 I10 J0 E2\n")
        segs = index.layers[0].segs
        self.assertGreaterEqual(len(segs) // 4, 18)
        for i in range(0, len(segs), 4):
            self.assertAlmostEqual(math.hypot(segs[i + 2] - 10, segs[i + 3]), 10, places=3)
        # Counter-clockwise from (0, 0) to (20, 0) goes below the centre.
        self.assertLess(min(segs[1::2]), -9.9)
        self.assertEqual((round(segs[-2], 3), round(segs[-1], 3)), (20, 0))

    def test_tools_for_multicolour_prints(self):
        index = read("M83\n;LAYER_CHANGE\nT0\nG1 X0 Y0\nG1 X10 Y0 E1\nT1\nG1 X10 Y10 E1\n"
                     "; filament_colour = #2B2A2D;#C33F31\n")
        self.assertEqual(list(index.layers[0].tools), [0, 1])
        self.assertEqual(index.colours, ["#2B2A2D", "#C33F31"])
        self.assertEqual(index.layer_json(0)["tools"], [0, 1])

    def test_no_layer_markers_uses_z(self):
        index = read("M83\nG1 Z0.2\nG1 X0 Y0\nG1 X10 Y0 E1\nG1 Z0.4\nG1 X10 Y10 E1\nG1 Z10\nG1 X0 Y0\n")
        self.assertEqual([round(layer.z, 2) for layer in index.layers], [0.2, 0.4])

    def test_without_time_marks_layer_progress_is_by_bytes(self):
        index = read(SAMPLE)
        self.assertIsNone(index.time_at(100))
        second = index.layers[2]
        done, left = index.layer_progress((second.start + second.ends[-1]) // 2)
        self.assertAlmostEqual(done, 0.5, delta=0.01)
        self.assertIsNone(left)

    def test_time_between_marks_goes_by_the_moves(self):
        # 100 s between two marks: lots of quick detail (most of the bytes),
        # then one long, slow line (most of the time).
        quick = "".join(f"G1 X{10 + k % 2} Y10 E0.01 F12000\n" for k in range(300))
        text = f"M83\n;TIME_ELAPSED:0\n{quick}G1 X300 Y10 E15 F300\n;TIME_ELAPSED:100\n"
        index = read(text)
        slow = text.encode().index(b"G1 X300")
        self.assertLess(index.time_at(slow // 2), 5)  # by bytes, it would be about 50
        self.assertLess(index.time_at(slow), 10)
        self.assertEqual(index.time_at(len(text)), 100)

    def test_the_moves_own_time(self):
        index = read("G90\nG1 X10 Y0 F600\nG4 P2000\nG2 X10 Y0 I10 J0 F600\nG1 E6 F60\n")
        # 10 mm at 10 mm/s, a 2 s pause, a 10 mm radius circle, 6 mm of
        # filament at 1 mm/s.
        self.assertAlmostEqual(index.moves_at(index.file_size), 1 + 2 + 2 * math.pi + 6, places=3)

    def test_the_tools_the_job_uses(self):
        self.assertEqual(read(SAMPLE).tools, [0])
        self.assertEqual(read("M83\nT1\nG1 X10 E1 F600\nT3\nG1 X20 E1\nT2\n").tools, [1, 3])  # T2 prints nothing

    def test_the_start_codes_time(self):
        self.assertEqual(read(SAMPLE).start_code_time(), 0)
        # Just after the mark before the first layer.
        timed = read(TIMED.replace(";LAYER_CHANGE", ";TIME_ELAPSED:5\n;LAYER_CHANGE", 1))
        self.assertAlmostEqual(timed.start_code_time(), 5, delta=1)

    def test_layer_progress_by_the_slicers_times(self):
        text = TIMED.encode()
        index = read(TIMED)
        mark = text.index(b";TIME_ELAPSED:12")
        self.assertEqual(index.time_at(mark), 12)
        self.assertEqual(index.time_at(mark // 2), 6)  # from 0 at the start of the file
        self.assertEqual(index.time_at(len(text)), 30)  # past the last mark
        self.assertEqual(index.file_size, len(text))
        first, second = index.layers[1], index.layers[2]
        self.assertEqual(index.layer_progress(first.start)[0], 0)
        done, left = index.layer_progress(second.start)
        self.assertEqual(done, 0)
        end = index.time_at(second.ends[-1])
        self.assertAlmostEqual(left, end - index.time_at(second.start))
        self.assertEqual(index.layer_progress(second.ends[-1]), (1, 0))
        # Past the last layer's printing (end code): still that layer, done.
        self.assertEqual(index.layer_progress(len(text))[0], 1)

    def test_no_layers(self):
        self.assertIsNone(read("G28\n").layer_progress(0))

    def test_layer_json(self):
        data = read(SAMPLE).layer_json(1)
        self.assertEqual((data["layer"], data["layers"], data["z"]), (1, 3, 0.2))
        self.assertEqual(len(data["segs"]), 4 * len(data["ends"]))
        self.assertIsNone(data["tools"])  # one filament


if __name__ == "__main__":
    unittest.main()
